# Membuat lists yang berisi nama-nama hewan
animals = ["Kucing", "Kelinci", "Burung"]
# Mengakses item berdasarkan urutannya (indexing), indexing dimulai dari angka 0
print(animals[1]) # Kelinci
# Negative indexing: -1 berarti item terakhir, -2 berarti item kedua dari belakang
print(animals[-1]) # Burung
print(animals[-2]) # Kelinci
